-- ============================================================================
-- table: public.generations
-- ============================================================================
-- immutable table for tracking AI flashcard generation events
-- each record represents a single AI generation session
-- ============================================================================

create table public.generations (
  -- primary key: unique identifier for each generation event
  id uuid primary key default uuid_generate_v4(),
  
  -- foreign key: links to the user who initiated the generation
  -- on delete cascade ensures all generations are deleted when user is deleted
  user_id uuid not null references auth.users(id) on delete cascade,
  
  -- the source text provided by the user for AI generation
  -- constrained to 1000-10000 characters as per PRD requirements
  source_text text not null check (
    char_length(source_text) >= 1000 and 
    char_length(source_text) <= 10000
  ),
  
  -- optional context/topic provided by the user to improve AI generation quality
  -- nullable field allows users to generate without providing context
  context text,
  
  -- identifier of the AI model used for generation
  -- examples: "gpt-4", "claude-3-sonnet", "gpt-3.5-turbo"
  -- stored as text for flexibility to support different AI providers
  ai_model text not null,
  
  -- time taken to generate flashcards in milliseconds
  -- must be non-negative, useful for performance monitoring
  generation_time_ms integer not null check (generation_time_ms >= 0),
  
  -- number of flashcards successfully generated in this event
  -- denormalized for quick analytics without joining to flashcards table
  -- must be non-negative
  flashcards_generated_count integer not null check (flashcards_generated_count >= 0),
  
  -- cost of the API call in USD
  -- stored with 6 decimal precision for accurate tracking of small API costs
  -- default 0 allows for free tiers or models without cost
  -- must be non-negative
  cost numeric(10,6) not null default 0 check (cost >= 0),
  
  -- timestamp of when the generation event was completed
  -- no updated_at column as this table is immutable by design
  created_at timestamptz not null default now()
);

-- ============================================================================
-- alter table: public.flashcards
-- ============================================================================
-- add generation_id column to link flashcards to generation events
-- ============================================================================

-- add generation_id column as nullable foreign key
-- nullable allows for manually created flashcards (not generated by AI)
-- on delete set null preserves flashcards even if generation record is deleted
-- this maintains data integrity while allowing generation history cleanup
alter table public.flashcards
add column generation_id uuid references public.generations(id) on delete set null;

-- ============================================================================
-- indexes for flashcards table
-- ============================================================================

-- index on generation_id
-- purpose: optimizes queries fetching all flashcards from a specific generation event
-- typical query: select * from flashcards where generation_id = '...'
-- supports null values for manually created flashcards
create index flashcards_generation_id_idx on public.flashcards(generation_id);

-- ============================================================================
-- indexes for generations table
-- ============================================================================

-- index on user_id
-- purpose: optimizes queries fetching generation history for a specific user
-- typical query: select * from generations where user_id = '...'
-- use cases: analytics, user generation history, cost tracking per user
create index generations_user_id_idx on public.generations(user_id);

-- index on created_at with descending order
-- purpose: optimizes queries fetching recent generations in chronological order
-- typical query: select * from generations order by created_at desc limit 10
-- use cases: admin dashboards, recent activity feeds, generation history
create index generations_created_at_idx on public.generations(created_at desc);

-- ============================================================================
-- row level security (rls) for generations table
