-- enable rls on the generations table
-- this ensures that all queries are subject to rls policies
alter table public.generations enable row level security;

-- ----------------------------------------------------------------------------
-- rls policies for anon role (unauthenticated users)
-- ----------------------------------------------------------------------------
-- rationale: anonymous users should have no access to generations data
-- all operations return false, effectively denying all access
-- generations contain sensitive user data and API usage information

-- anon: select policy
-- denies anonymous users from viewing any generation records
create policy "anon_users_cannot_view_generations"
on public.generations
for select
to anon
using (false);

-- anon: insert policy
-- denies anonymous users from creating generation records
-- only authenticated users can trigger AI generation
create policy "anon_users_cannot_create_generations"
on public.generations
for insert
to anon
with check (false);

-- anon: update policy
-- denies anonymous users from updating generation records
-- generations are immutable, but this policy prevents any attempts
create policy "anon_users_cannot_update_generations"
on public.generations
for update
to anon
using (false)
with check (false);

-- anon: delete policy
-- denies anonymous users from deleting generation records
create policy "anon_users_cannot_delete_generations"
on public.generations
for delete
to anon
using (false);

-- ----------------------------------------------------------------------------
-- rls policies for authenticated role (logged-in users)
-- ----------------------------------------------------------------------------
-- rationale: authenticated users can only access their own generation records
-- all policies check that auth.uid() matches the generation's user_id
-- this ensures data isolation and privacy

-- authenticated: select policy
-- allows users to view only their own generation records
-- enables users to review their generation history and costs
create policy "authenticated_users_can_view_own_generations"
on public.generations
for select
to authenticated
using (auth.uid() = user_id);

-- authenticated: insert policy
-- allows users to create generation records only for themselves
-- with check ensures user_id is set to the authenticated user's id
-- prevents users from creating generation records for other users
create policy "authenticated_users_can_create_own_generations"
on public.generations
for insert
to authenticated
with check (auth.uid() = user_id);

-- authenticated: update policy
-- allows users to update only their own generation records
-- note: while the table is designed to be immutable, this policy allows
-- for edge cases such as correcting metadata or administrative adjustments
-- using clause prevents viewing others' data, with check prevents changing ownership
create policy "authenticated_users_can_update_own_generations"
on public.generations
for update
to authenticated
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

-- authenticated: delete policy
-- allows users to delete only their own generation records
-- enables users to clean up their generation history if desired
create policy "authenticated_users_can_delete_own_generations"
on public.generations
for delete
to authenticated
using (auth.uid() = user_id);

